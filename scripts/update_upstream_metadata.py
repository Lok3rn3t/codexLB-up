"""Refresh bundled upstream metadata: uv run python scripts/update_upstream_metadata.py."""

from __future__ import annotations

import asyncio
import json
import sys
from pathlib import Path
from urllib.request import Request, urlopen

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from app.core.clients.codex_version import CodexVersionCache  # noqa: E402
from app.core.metadata_store import write_metadata  # noqa: E402
from app.core.types import JsonValue  # noqa: E402
from app.core.usage.pricing_catalog import (  # noqa: E402
    BUNDLE_PATH,
    LITELLM_URL,
    MAX_CATALOG_BYTES,
    MODELS_DEV_URL,
    decode_snapshot,
    encode_snapshot,
    merge_catalogs,
    parse_litellm,
    parse_models_dev,
)


def fetch(url: str) -> JsonValue:
    request = Request(url, headers={"User-Agent": "codex-lb", "Accept": "application/json"})
    with urlopen(request, timeout=30) as response:
        body = response.read(MAX_CATALOG_BYTES + 1)
        if len(body) > MAX_CATALOG_BYTES:
            raise ValueError("Upstream metadata response too large")
        return json.loads(body)


def public_release_models(payload: JsonValue) -> list[dict[str, JsonValue]]:
    entries = payload.get("models") if isinstance(payload, dict) else None
    if not isinstance(entries, list):
        raise ValueError("Missing Codex models")
    models: dict[str, dict[str, JsonValue]] = {}
    for entry in entries:
        if not isinstance(entry, dict):
            raise ValueError("Malformed Codex model entry")
        slug = entry.get("slug")
        if not isinstance(slug, str) or not slug.strip():
            raise ValueError("Missing Codex model slug")
        if (
            entry.get("visibility") != "list"
            or entry.get("supported_in_api") is not True
            or entry.get("shell_type") != "shell_command"
            or entry.get("model_specialty")
            or entry.get("allow_only_chatgpt_workspace_executor")
            or entry.get("allow_only_codex_cloud_agent_orchestrator")
        ):
            continue
        window = entry.get("context_window")
        plans = entry.get("available_in_plans")
        name = entry.get("display_name")
        if (
            slug in models
            or not isinstance(window, int)
            or isinstance(window, bool)
            or window <= 0
            or not isinstance(plans, list)
            or not plans
            or not all(isinstance(plan, str) and plan for plan in plans)
            or not isinstance(name, str)
            or not name.strip()
        ):
            raise ValueError(f"Invalid or duplicate public Codex model: {slug}")
        # As in the compatibility bundle, account discovery supplies upstream prompt text.
        models[slug] = {k: v for k, v in entry.items() if k not in {"base_instructions", "model_messages"}}
    if not models:
        raise ValueError("Codex supplied no public models")
    return list(models.values())


async def main() -> None:
    # Generation requires both sources; never commit a degraded/partial snapshot.
    primary = parse_models_dev(await asyncio.to_thread(fetch, MODELS_DEV_URL))
    secondary = parse_litellm(await asyncio.to_thread(fetch, LITELLM_URL))
    prices = merge_catalogs(primary, secondary)
    version = await CodexVersionCache()._fetch_latest_version()
    if version is None:
        raise RuntimeError("No stable Codex release found")
    url = f"https://raw.githubusercontent.com/openai/codex/rust-v{version}/codex-rs/models-manager/models.json"
    models = public_release_models(await asyncio.to_thread(fetch, url))
    model_snapshot = json.dumps({"source": url, "models": models}, indent=2, allow_nan=False) + "\n"
    previous = json.loads(BUNDLE_PATH.read_text()) if BUNDLE_PATH.exists() else None
    if previous is not None:
        prices = merge_catalogs(prices, decode_snapshot(previous))
    content = encode_snapshot(prices)
    if previous is None or "updated_at" not in previous or decode_snapshot(previous) != prices:
        write_metadata(BUNDLE_PATH, content)
    write_metadata(ROOT / "app/core/openai/codex_models_snapshot.json", model_snapshot)
    write_metadata(
        ROOT / "app/core/clients/codex_version_snapshot.py",
        f'# Generated by scripts/update_upstream_metadata.py; do not edit manually.\nCODEX_VERSION = "{version}"\n',
    )
    print(f"Updated {len(prices)} prices and {len(models)} public models from Codex {version}")


if __name__ == "__main__":
    asyncio.run(main())
